    '    return String(s == null ? "" : s).replace(/[&<>"\\\']/g, function(c){',
    '      return ({"&":"&amp;","<":"&lt;",">":"&gt;","\\"":"&quot;","\\\'":"&#39;"})[c];',
    '    });',
    '  }',
    '  function fmtMoney(n) {',
    '    var v = parseFloat(n);',
    '    if (!isFinite(v) || v === 0) return "";',
    '    return "$" + v.toLocaleString("en-US", {minimumFractionDigits: 2, maximumFractionDigits: 2});',
    '  }',
    '  function fmtDate(s) {',
    '    if (!s) return "";',
    '    var d = new Date(s);',
    '    if (isNaN(d.getTime())) return escapeHtml(s);',
    '    return d.toLocaleDateString();',
    '  }',
    '  function buildGrades(b) {',
    '    var rg = b.roboGrade || {};',
    '    var pips = [];',
    '    if (rg.score != null) pips.push(\'<div class="grade-pip rg"><span class="lbl">RG</span>\' + Math.round(rg.score) + \'</div>\');',
    '    if (b.cgcGrade) pips.push(\'<div class="grade-pip cgc-real"><span class="lbl">CGC</span>\' + escapeHtml(b.cgcGrade) + \'</div>\');',
    '    else if (b.assessedCGCGrade) pips.push(\'<div class="grade-pip cgc"><span class="lbl">CGC AI</span>\' + escapeHtml(b.assessedCGCGrade) + \'</div>\');',
    '    if (b.psaGrade) pips.push(\'<div class="grade-pip psa-real"><span class="lbl">PSA</span>\' + escapeHtml(b.psaGrade) + \'</div>\');',
    '    else if (b.assessedPSAGrade) pips.push(\'<div class="grade-pip psa"><span class="lbl">PSA AI</span>\' + escapeHtml(b.assessedPSAGrade) + \'</div>\');',
    '    return pips.join("");',
    '  }',
    '  function buildRgComponents(rg) {',
    '    if (rg.frontScore == null && rg.backScore == null && rg.spineScore == null && rg.interiorScore == null) return "";',
    '    var parts = [',
    '      [rg.frontScore, "FRONT", 50],',
    '      [rg.backScore, "BACK", 20],',
    '      [rg.spineScore, "SPINE", 20],',
    '      [rg.interiorScore, "INTERIOR", 10]',
    '    ];',
    '    var h = \'<div class="rg-components">\';',
    '    parts.forEach(function(p){',
    '      var n = p[0] != null ? Math.round(p[0]) : "\u2014";',
    '      h += \'<div class="rg-comp"><div class="n">\' + n + \'</div><div class="l">\' + p[1] + \' / \' + p[2] + \'</div></div>\';',
    '    });',
    '    h += "</div>";',
    '    return h;',
    '  }',
    '  function buildDefects(rg) {',
    '    if (!rg.defects || !rg.defects.length) return "";',
    '    var grouped = { Front: [], Back: [], Spine: [], Interior: [] };',
    '    rg.defects.forEach(function(d){',
    '      var cat = d.category || "Front";',
    '      if (!grouped[cat]) grouped[cat] = [];',
    '      grouped[cat].push(d);',
    '    });',
    '    var h = \'<div class="defects">\';',
    '    Object.keys(grouped).forEach(function(cat){',
    '      var defs = grouped[cat];',
    '      if (!defs.length) return;',
    '      h += \'<div style="margin-bottom:4px"><strong>\' + cat + \':</strong> \';',
    '      h += defs.map(function(d){',
    '        var sev = (d.severity || "").toLowerCase();',
    '        var cls = sev === "high" ? "d high" : sev === "med" ? "d med" : sev === "low" ? "d low" : "d";',
    '        var txt = escapeHtml(d.type || "defect");',
    '        if (d.location) txt += " (" + escapeHtml(d.location) + ")";',
    '        if (d.measurement) txt += " " + escapeHtml(d.measurement);',
    '        return \'<span class="\' + cls + \'">\' + txt + \'</span>\';',
    '      }).join(" ");',
    '      h += "</div>";',
    '    });',
    '    h += "</div>";',
    '    return h;',
    '  }',
    '  function buildCosts(b) {',
    '    var rows = [',
    '      ["Date acquired", fmtDate(b.dateAcquired)],',
    '      ["Purchase price", fmtMoney(b.purchasePrice)],',
    '      ["Taxes/fees/shipping", fmtMoney(b.taxesFeesShipping)],',
    '      ["Grading cost", fmtMoney(b.gradingCost)],',
    '      ["CGC return shipping", fmtMoney(b.cgcShipping)],',
    '      ["FMV", fmtMoney(b.fmv) + (b.fmvDate ? " (" + fmtDate(b.fmvDate) + ")" : "")]',
    '    ].filter(function(r){ return r[1] && r[1].length; });',
    '    var costFields = [b.purchasePrice, b.taxesFeesShipping, b.gradingCost, b.cgcShipping];',
    '    var total = costFields.reduce(function(s, v){ var n = parseFloat(v); return s + (isFinite(n) ? n : 0); }, 0);',
    '    if (rows.length === 0 && total === 0) return "";',
    '    var h = \'<div class="costs">\';',
    '    rows.forEach(function(r){',
    '      h += \'<div class="row"><span class="lbl">\' + r[0] + \'</span><span class="val">\' + r[1] + \'</span></div>\';',
    '    });',
    '    if (total > 0) {',
    '      h += \'<div class="row total"><span class="lbl">Total cost</span><span class="val">\' + fmtMoney(total) + \'</span></div>\';',
    '    }',
    '    h += "</div>";',
    '    return h;',
    '  }',
    '  function buildImgs(folder, count) {',
    '    var labels = ["front_cover", "back_cover", "page_quality", "raking_light"];',
    '    var captions = ["Front Cover", "Back Cover", "Page Quality", "Raking Light"];',
    '    var h = \'<div class="imgs">\';',
    '    var max = Math.min(count, 4);',
    '    for (var i = 0; i < max; i++) {',
    '      var slot = labels[i] || ("image_" + (i+1));',
    '      var cap = captions[i] || ("Image " + (i+1));',
    '      var src = folder + "/" + slot + ".jpg";',
    '      h += \'<div class="img-tile" data-src="\' + src + \'">\';',
    '      h += \'<img src="\' + src + \'" alt="\' + cap + \'" onerror="this.parentElement.dataset.src=this.src=\\\'\' + folder + \'/\' + slot + \'.png\\\';this.onerror=null">\';',
    '      h += \'<div class="cap">\' + cap + \'</div>\';',
    '      h += "</div>";',
    '    }',
    '    h += "</div>";',
    '    return h;',
    '  }',
    '  function section(title, body) {',
    '    if (!body) return "";',
    '    return \'<div class="section"><div class="sect-h">\' + title + \'</div>\' + body + \'</div>\';',
    '  }',
    '  function buildNotesList(notes) {',
    '    if (!notes) return "";',
    '    var lines = String(notes).split(/\\n+/).map(function(s){ return s.trim(); }).filter(Boolean);',
    '    if (!lines.length) return "";',
    '    if (lines.length === 1) return \'<div class="narrative">\' + escapeHtml(lines[0]) + \'</div>\';',
    '    return \'<ul class="notes-list">\' + lines.map(function(l){',
    '      var clean = l.replace(/^[\\u2022\\-\\*]\\s*/, "");',
    '      return "<li>" + escapeHtml(clean) + "</li>";',
    '    }).join("") + "</ul>";',
    '  }',
    '  var content = document.getElementById("content");',
    '  BOOKS.forEach(function(b){',
    '    var div = document.createElement("div");',
    '    div.className = "book";',
    '    var rg = b.roboGrade || {};',
