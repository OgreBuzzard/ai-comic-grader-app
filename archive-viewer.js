// Robograder — Offline archive viewer module
// Loaded dynamically when the user clicks "Export Collection" in Settings.
// Self-contained: no app state required; called with collection data as args.

export { makeSafeBookName, buildArchiveViewer };

// Helper: produce a filesystem-safe folder name from a comic record.
// Lowercase, alphanumeric + underscore only, with title and issue both in the name.
function makeSafeBookName(c) {
  const title = (c.title || 'unknown').toLowerCase().replace(/[^a-z0-9]/g, '_').replace(/_+/g, '_').replace(/^_|_$/g, '');
  const issue = c.issue ? `_${String(c.issue).replace(/[^a-z0-9]/gi, '')}` : '';
  return `${title}${issue}`.slice(0, 80); // cap length
}

// Builds a self-contained HTML archive that can be opened from the unzipped folder.
// The collection data is embedded inline as a JSON literal so no fetch() is needed —
// avoids the file:// CORS restrictions that block sibling-file access in Safari and
// Chrome when the user double-clicks the HTML.
//
// Built as an array of plain strings (not a single template literal) to avoid
// escape-character ambiguity with the nested backticks inside the embedded script.
